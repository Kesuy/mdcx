from mdcx.consts import LOCAL_VERSION


def build_usage_guide(version: str = LOCAL_VERSION) -> str:
    return f"""📘 MDCx {version} 使用说明
────────────────────────────────────────────────────────

🎬 软件用途
MDCx 用于读取影片、联网刮削元数据、生成 NFO、下载图片与预告片，并按规则整理本地媒体文件。
可配合 Emby、Jellyfin、Kodi、Plex 等媒体库使用。

🚀 第一次使用
1. 打开【设置】-【刮削目录】，选择待刮削目录，并确认成功、失败输出目录。
2. 打开【设置】-【刮削模式】，选择正常、视频、更新或读取模式。
3. 在【刮削网站】设置站点顺序；需要代理或 Cookie 的站点，请到【网络】完成配置。
4. 按需检查【下载】【命名】【翻译】【字幕】【水印】【NFO】【演员】等页面。
5. 点击底部【保存】，回到主界面选择目录，再点击【开始】。

🧭 四种刮削模式
• 正常模式：联网获取字段和图片，可生成 NFO，并按设置移动、重命名文件。
• 视频模式：联网获取影片信息，只整理视频，不下载图片和 NFO。
• 更新模式：适合已经归类的媒体库，按更新规则重新获取或更新信息。
• 读取模式：优先读取本地 NFO，可离线检查、重命名或重新整理；重新下载资源时仍需联网。

🪟 主界面与日志
• 可拖动左侧导航栏边缘调整导航宽度。
• 可拖动影片详情与右侧结果列表之间的分隔线；封面和缩略图会保持原始比例缩放。
• 右侧结果支持按完成顺序、番号或演员排序，也可以切换升序与降序。
• 【选择目录】旁的文件按钮可加载本地 NFO；编辑、打开目录、播放等操作位于影片信息区。
• 【日志】上半区显示任务信息，下半区显示请求信息；左下角按钮可显示或隐藏请求日志。
• 失败列表可在日志页查看并保存。启用保存日志后，文本日志位于程序目录的 Log 文件夹。

⚙️ 设置与配置
• 支持多个 JSON 配置；底部可切换配置、另存为、恢复默认并保存。
• 命名规则使用模板字段，建议先查看页面中的实时预览，再执行批量整理。
• 站点优先级决定字段与图片的获取顺序；“字段优先”会按设置尝试多个来源。
• 字幕、图片、水印、演员资料、NFO 字段和高级行为均可独立控制。
• 旧版 INI 配置会自动迁移，请保留原配置文件，不要通过删除配置解决升级问题。

🌐 网络、代理与 Cookie
• 先到【设置】-【网络】填写代理，再打开左侧【检测网络】验证各站点连通性。
• JavDB、JavBus、FC2CMADB 等需要登录状态时，可在网络设置中填写并检查 Cookie。
• 遇到 Cloudflare 挑战时，可配置本地 CF Bypass 或 FlareSolverr 服务地址。
• 检测失败时依次检查：代理地址和端口、代理软件是否运行、站点 Cookie、节点地区和系统时间。
• 检测过程可点击【停止检测】取消，不需要强制关闭软件。

🧰 常用工具
• 软链接适合网盘或跨盘媒体；硬链接适合同盘保种，操作前请确认平台和文件系统支持。
• 工具页可批量处理字幕、演员资料、额外图片、主题视频和软链接。
• 文件清理会影响真实文件。请先核对规则、目录和排除项，再勾选确认并执行。

🛡️ 安全建议
• 第一次使用新配置时，先用少量影片测试命名、移动、NFO 和图片结果。
• 批量整理前备份重要媒体与配置；不要让成功目录、失败目录互相包含。
• 读取模式和更新模式也可能按设置修改文件，执行前请再次确认更新规则。
• 网络站点可能临时失效或限制访问，请结合【检测网络】和【日志】判断具体原因。

🔄 更新与反馈
• 左下角可检查最新版本；升级后原配置应继续兼容。
• 项目与版本发布：https://github.com/Kesuy/mdcx

💡 提示：界面上的问号按钮包含对应设置项的详细说明，可与本页配合查看。
"""


def setup_usage_guide(window) -> None:
    browser = window.Ui.textBrowser_about
    browser.setPlainText(build_usage_guide())
    browser.setOpenExternalLinks(False)
    browser.moveCursor(browser.textCursor().MoveOperation.Start)
